      contact: (sec(18).match(/(?:담당\s*부서|부서명?)\s*[:：]?\s*([가-힣A-Za-z0-9]{2,15}(?:과|팀|실|센터|부|국|처))/) || [])[1] || '개인정보 보호 담당부서',
